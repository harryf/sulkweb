function verifyBoard(name: string, exp: Expected) {
  const m = loadMission(name as never);
  it(`${name}: square set matches the original exactly`, () => {
    expect(m.squares.map(s => `${s.x},${s.y}`).sort()).toEqual(exp.sections.flat().sort());
  });
  it(`${name}: section partition matches the source sublists`, () => {
    expect(new Set(m.squares.map(s => s.section)).size).toBe(exp.sections.length);
    for (const [i, section] of exp.sections.entries()) {
      const ids = new Set(section.map(key => {
        const [x, y] = key.split(',').map(Number);
        return m.squares.find(s => s.x === x && s.y === y)!.section;
      }));
      expect(ids, `section ${i}`).toEqual(new Set([i]));
    }
  });
  it(`${name}: doors and entries match; exits where present`, () => {
    expect(m.squares.filter(s => s.doorFacing).map(s => `${s.x},${s.y}:${s.doorFacing}`).sort())
      .toEqual([...exp.doors].sort());
    expect((m.entryPoints ?? []).map(e => `${e.x},${e.y}`).sort()).toEqual([...exp.entries].sort());
    if (exp.exits) {
      expect((m.exitPoints ?? []).map(e => `${e.x},${e.y}`).sort()).toEqual([...exp.exits].sort());
    }
  });
  it(`${name}: boots a legal engine`, () => {
    const engine = new GameEngine(m, [], new SeededRng(1));
    expect(engine.marines.length).toBe(m.marineDeployment!.length);
    expect(engine.state.result).toBe('ongoing');
  });
  return m;
}

